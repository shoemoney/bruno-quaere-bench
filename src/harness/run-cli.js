// ---------------------------------------------------------------------------
// the bru shim (Addendum F: "sandbox/bin/bru is a logging shim first on PATH")
// ---------------------------------------------------------------------------

// The shim is plain CommonJS-free Node run directly (`#!/usr/bin/env node`), not an ESM module of
// this project -- it is written to disk as a standalone file the CLI's own shell/exec resolves by
// name, with no import graph back into src/. It appends one JSON line per invocation to
// turns.jsonl (Addendum F: "Turns = shim lines") before execing the real bru synchronously and
// exiting with its exact code, so from the CLI's point of view it IS bru.
function bruShimSource(realBruPath) {
  const escapedPath = JSON.stringify(realBruPath);
  return `#!/usr/bin/env node
// Auto-generated by src/harness/run-cli.js -- do not edit by hand. Logs every invocation to
// ../turns.jsonl, then execs the real bru (${realBruPath}) with the same argv and stdio.
const { appendFileSync } = require('node:fs');
const { spawnSync } = require('node:child_process');
const path = require('node:path');

const argv = process.argv.slice(2);
const turnsPath = path.join(__dirname, '..', 'turns.jsonl');
try {
  appendFileSync(turnsPath, JSON.stringify({ ts: new Date().toISOString(), argv }) + '\\n');
} catch {
  // best-effort logging only; never block the real invocation over it
}

const result = spawnSync(${escapedPath}, argv, { stdio: 'inherit' });
if (result.error) {
  process.stderr.write(String(result.error.message || result.error) + '\\n');
  process.exit(1);
}
process.exit(result.status === null ? 1 : result.status);
`;
}

// installBruShim(sandboxDir) -> shim path. Creates sandboxDir/bin/bru; the caller is responsible
// for putting sandboxDir/bin first on the spawned process's PATH.
async function installBruShim(sandboxDir) {
  const binDir = path.join(sandboxDir, 'bin');
  await mkdir(binDir, { recursive: true });
  const realBru = resolveBru();
  const shimPath = path.join(binDir, 'bru');
  await writeFile(shimPath, bruShimSource(realBru), 'utf8');
  await chmod(shimPath, 0o755);
  // The shim has no file extension (it must be named exactly `bru` for PATH lookup to find it),
  // so Node's CJS-vs-ESM detection for running it directly falls back to the nearest package.json
  // -- which, depending on where --out lands, could easily be this project's own ("type":
  // "module"). Pin bin/'s own package.json so the shim's require()s always resolve as CommonJS,
  // regardless of outDir's location relative to any other package.json.
  await writeFile(path.join(binDir, 'package.json'), '{"type":"commonjs"}\n', 'utf8');
  return shimPath;
}

async function readShimTurns(sandboxDir) {
  try {
    const text = await readFile(path.join(sandboxDir, 'turns.jsonl'), 'utf8');
    return text
      .split('\n')
      .filter((line) => line.trim().length > 0)
      .map((line) => {
        try {
          return JSON.parse(line);
        } catch {
          return { raw: line };
        }
      });
  } catch {
    return [];
  }
}

