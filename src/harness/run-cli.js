// resolveCliAdapter(name): dynamically imports src/harness/cli/index.js -- a sibling workstream's
// module (ARCHITECTURE Addendum F "Files") -- so this file loads cleanly (and its tests can inject
// a fake adapter via climb()'s `cli` param) even if that module, or one adapter under it, isn't
// there yet. Contract (index.js's own docstring): `loadAdapter(name) -> {name,
// build({sandbox, prompt, model, home}) -> {cmd, args, env, cwd?}, parseUsage(stdout, home) ->
// {tokensIn, tokensCached, tokensOut, modelVersion, usageEstimated}, resume(sessionId, {sandbox,
// prompt, model, home}) -> {cmd, args, env, cwd?}}`.
async function resolveCliAdapter(name) {
  let mod;
  try {
    mod = await import('./cli/index.js');
  } catch (err) {
    throw new Error(
      `--cli ${name}: could not load src/harness/cli/index.js (${err.message}). ` +
        'That module is a separate workstream per ARCHITECTURE Addendum F; pass an adapter object ' +
        'directly via climb({cli: ...}) until it lands.',
    );
  }
  if (typeof mod.loadAdapter === 'function') return mod.loadAdapter(name);
  throw new Error(`src/harness/cli/index.js has no loadAdapter() export -- cannot resolve --cli ${name}`);
}

