// One model, one seed, one CLI-driven climb (ARCHITECTURE Addendum F) -> RunResult. The
// counterpart to run.js's message-loop climb(), for the case where "the agent" is a real product
// -- claude code's `ai`, `codex`, `qwen`, `gemini`, `kimi`, or (in tests) a fake stand-in -- run as
// its own subprocess against a sandbox we prepare, rather than a tool-calling loop we drive
// ourselves turn by turn. The harness never sees the CLI's reasoning; it only watches the admin
// log for submissions and the process for usage and exit.
//
// Wall-clock timing (Date.now()) is allowed throughout: this is the harness, never anything that
// feeds an artifact, a spec, a skill, or a rung (ARCHITECTURE.md's determinism rule).

