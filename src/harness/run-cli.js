// climb({cliName, model, seed, attempt, budgetTokens, wallMsLimit, outDir, skillMode, skillBytes,
// pollMs, publicPort?, adminPort?, cli?, topRung?}) -> RunResult
//
// Two escape hatches beyond ARCHITECTURE.md's literal signature, both for tests rather than a
// real run (same pattern run.js uses for its own `driver` param):
//   - `cli`: a pre-built adapter object, skipping --cli/src/harness/cli/index.js resolution
//     entirely, so a test can climb against a scripted fake process instead of a real CLI binary.
//   - `publicPort`/`adminPort`/`topRung`: normally 0 / 0 / 99; a test that wants a pinned base URL
//     or a short climb (pass at rung 0 IS the top) can override them.
// --- Addendum G follow-up: let a killed CLI's own shutdown writes land before reading them ------
//
// The drain gets the process to exit, but an agent CLI writes its usage/session records DURING
// shutdown, and `parseUsage` used to run the instant supervise.js resolved. Measured on a real
// rung-0 qwen kill: `$HOME/.qwen/usage_record.jsonl` was written at 18:44:17.952 and parseUsage
// read it at 18:44:17.953 -- a one-millisecond race that cost the run its tokens AND its model,
// with the correct answer sitting on disk a blink later. So after a supervised kill, re-read for
// a short settle window instead of taking the first miss as final. Wall-clock waiting is fine
// here: this is the harness, never anything that feeds an artifact, a spec, a skill, or a rung.
const USAGE_SETTLE_MS = 250;
const USAGE_SETTLE_ATTEMPTS = 8; // ~2s of settle in total, negligible against a climb

// parseUsageSettling(adapter, stdout, homeDir, supervisedKill) -> usage, or throws the adapter's
// own last error. On a clean exit this is exactly one parseUsage() call (no settle, no delay). On
// a supervised kill it retries while the adapter is still reporting nothing usable -- a throw, or
// a usageEstimated result, which is how an adapter with its own estimate fallback (kimi) says
// "I found no real numbers" without throwing.
async function parseUsageSettling(adapter, stdout, homeDir, supervisedKill) {
  const attempts = supervisedKill ? USAGE_SETTLE_ATTEMPTS : 1;
  let lastError = null;
  let lastEstimate = null;
  for (let attempt = 0; attempt < attempts; attempt += 1) {
    if (attempt > 0) {
      // eslint-disable-next-line no-await-in-loop
      await new Promise((resolve) => setTimeout(resolve, USAGE_SETTLE_MS));
    }
    let usage;
    try {
      // eslint-disable-next-line no-await-in-loop
      usage = (await adapter.parseUsage(stdout, homeDir)) || {};
    } catch (err) {
      lastError = err;
      continue;
    }
    if (!usage.usageEstimated) return usage;
    lastEstimate = usage;
    lastError = null;
  }
  if (lastEstimate) return lastEstimate;
  throw lastError || new Error('cli climb: parseUsage returned no usage');
}

// prepareCliSandbox({world, sandboxDir, baseUrl, budgetTokens, skillMode, skillBytes}) -> writes
// the four documents climb() below hands the CLI before its first turn: spec.json,
// HOUSE-RULES.md, TASK.md, and (Addendum L) environments/local.yml -- the ONLY place
// world.auth.secret is ever written into a sandbox, since HOUSE-RULES.md/TASK.md both name the
// file but deliberately never state its value. Exported so test/sandbox-fidelity.test.js can
// prepare a real sandbox (the exact code path a CLI-driven climb uses) without spawning a CLI or
// running a full climb.
export async function prepareCliSandbox({
  world,
  sandboxDir,
  baseUrl,
  budgetTokens = 3_000_000,
  skillMode = 'sloppy',
  skillBytes = 5_000_000,
}) {
  await writeFile(path.join(sandboxDir, 'spec.json'), JSON.stringify(toOpenApi(world), null, 2));
  // HOUSE-RULES.md, not SKILL.md: a real CLI's own runtime auto-loads a file it recognizes by
  // name (SKILL.md, CLAUDE.md, ...) straight into context. This is 5 MB of deliberately sloppy
  // house documentation (Addendum A) -- finding it is the task, not something to hand it for free.
  await writeFile(
    path.join(sandboxDir, 'HOUSE-RULES.md'),
    toSkill(world, { mode: skillMode, targetBytes: skillBytes }),
  );
  await writeFile(
    path.join(sandboxDir, 'TASK.md'),
    buildTaskMd({ baseUrl, apiKey: world.auth.apiKey, budgetTokens }),
  );
  // mkdir first: writeFile here is the plain node:fs one, not sandbox.js's tool-facing writeFile
  // (which auto-creates parent directories) -- this path is the CLI-driven one, which never goes
  // through that tool surface at all.
  await mkdir(path.join(sandboxDir, path.dirname(LOCAL_ENV_PATH)), { recursive: true });
  await writeFile(
    path.join(sandboxDir, LOCAL_ENV_PATH),
    buildLocalEnv({ baseUrl, apiKey: world.auth.apiKey, secret: world.auth.secret }),
  );
}

// writeAmendedHouseRules({world, sandboxDir, rung, skillBytes}) -> the amendments dated at exactly
// `rung`, after rewriting HOUSE-RULES.md to the document as it reads from that rung on. Returns
// `[]` and touches nothing when no amendment lands there.
//
// Exported because it is the ONE place the sandbox's copy of the house rules is re-written, and
// because "did the document on disk actually change at rung 30" is a thing an operator wants to
// check against a real sandbox without driving a thirty-rung climb to get there.
export async function writeAmendedHouseRules({ world, sandboxDir, rung, skillBytes }) {
  const amendments = amendmentsAt(world, rung);
  if (amendments.length === 0) return [];
  await writeFile(
    path.join(sandboxDir, 'HOUSE-RULES.md'),
    toSkill(world, { mode: 'sloppy', atRung: rung, targetBytes: skillBytes }),
    'utf8',
  );
  return amendments;
}

export async function climb({
  cliName,
  cli: providedAdapter,
  model,
  seed,
  attempt = 1,
  budgetTokens = 3_000_000,
  wallMsLimit = DEFAULT_WALL_MS,
  outDir = 'runs',
  publicPort = 0,
  adminPort = 0,
  skillMode = 'sloppy',
  skillBytes = 5_000_000,
  pollMs = 2000,
  topRung = 99,
  // Addendum J: overridable only so a test can trip the cap in a handful of submissions instead
  // of 5000; a real run never passes this and gets the documented default.
  maxBruTurns = DEFAULT_MAX_BRU_TURNS,
  // Addendum P: injectable clock, purely for tests -- a fake `now()` lets a test jump the clock
  // forward (simulating a multi-hour sleep) between two loop iterations without actually
  // waiting. A real run never passes this and gets the real Date.now. Threaded through to
  // superviseProcess() too, so a sleep detected mid-spawn (inside its poll loop) uses the same
  // clock as gaps detected here, between spawns.
  now = Date.now,
  // Addendum Q rule 4 test hook: a pre-built world, skipping makeWorld(seed) -- see run.js's
  // identical param for the full rationale (world.amendments isn't produced by makeWorld() yet).
  world: providedWorld,
} = {}) {
  const world = providedWorld || makeWorld(seed);
  const label = model || (cliName ? `cli-${cliName}` : 'cli-fake');
  // Absolute, not relative: the sandbox path is handed to a CLI that has ALREADY chdir'd into the
  // sandbox (spawn cwd), so a relative `-C runs/.../sandbox` resolves against the sandbox itself
  // and the CLI dies with a bare "No such file or directory (os error 2)" before its first event.
  const runDir = path.resolve(outDir, String(label), String(seed), String(attempt));
  const sandboxDir = path.join(runDir, 'sandbox');
  const homeDir = path.join(runDir, 'home');
  await mkdir(sandboxDir, { recursive: true });
  await mkdir(homeDir, { recursive: true });

  await installBruShim(sandboxDir);

  // Addendum J: a fresh, unguessable secret every climb -- never derived from the seed and never
  // written anywhere the CLI's own sandbox (or its HOUSE-RULES.md/TASK.md) can read it.
  const adminToken = randomBytes(24).toString('hex');
  const server = createServer({ world, publicPort, adminPort, adminToken });
  const boundPorts = await server.start();
  const baseUrl = `http://127.0.0.1:${boundPorts.publicPort}`;
  const adminBase = `http://127.0.0.1:${boundPorts.adminPort}`;

  const startedAt = now();
  const transcript = [];
  let stoppedBecause = 'error';
  let allSubmissions = [];
  let tokensIn = 0;
  let tokensOut = 0;
  let tokensCached = 0;
  let tokensNovel = 0;
  let modelVersion = null;
  let modelMismatch = false;
  let usageEstimated = false;
  let sessionId = null;
  let resumes = 0;
  // Addendum Q rule 13 (CLI-driver fallback -- see the block above climb()).
  let codeWrites = 0;
  let docReads = 0;
  let sawAnyProcessOutput = false;

  // Addendum P: "the machine slept." Same rule as run.js's message loop -- a gap between two
  // consecutive ticks over SUSPEND_GAP_MS is a sleep/suspend, not the CLI working, and is folded
  // into `suspendedMs` (subtracted from elapsed before every wallMsLimit comparison). This loop's
  // own tick fires once per spawn/resume, between superviseProcess() calls; a sleep DURING one
  // spawn's own supervision window is detected by supervise.js's poll loop instead and reported
  // back on `outcome.suspendedMs`, folded in here right below.
  const SUSPEND_GAP_MS = 5 * 60 * 1000;
  let suspendedMs = 0;
  let lastTickAt = startedAt;
  function tick() {
    const t = now();
    const gap = t - lastTickAt;
    if (gap > SUSPEND_GAP_MS) suspendedMs += gap;
    lastTickAt = t;
    return t - startedAt - suspendedMs;
  }

  try {
    await adminPost(adminBase, '/admin/rungs', answerKey(world), adminToken);

    await prepareCliSandbox({ world, sandboxDir, baseUrl, budgetTokens, skillMode, skillBytes });

    // Addendum Q rule 4: rewrite HOUSE-RULES.md the moment the ladder reaches an amendment rung,
    // awaited from inside supervise.js's own serialized check chain (see its onAdvance doc
    // comment) so this always lands before the process's next poll tick. `amendmentsAt` is the
    // same resolver the rung text is built from, so the rewritten document and the sentence
    // telling the agent to go and read it always land together.
    async function applyAmendmentIfDue({ rung }) {
      const amendments = await writeAmendedHouseRules({ world, sandboxDir, rung, skillBytes });
      if (amendments.length === 0) return;
      transcript.push({
        ts: new Date().toISOString(),
        type: 'amendment',
        amendments: amendments.map((a) => ({ atRung: a.atRung, rule: a.rule, from: a.from, to: a.to })),
      });
    }

    const adapter = providedAdapter || (await resolveCliAdapter(cliName));

    const binDir = path.join(sandboxDir, 'bin');
    const pathWithShim = `${binDir}${path.delimiter}${process.env.PATH || ''}`;

    function buildEnv(extra) {
      // The shim goes first on PATH; the rest of the real PATH stays after it so the CLI's own
      // runtime (node, git, whatever it shells out to besides bru) still resolves normally --
      // Addendum F: "PATH keeps the original entries after it so the CLI's own runtime resolves."
      return { ...process.env, ...extra, PATH: pathWithShim };
    }

    // Seed the fresh per-run home with whatever credential the adapter needs there BEFORE the
    // first spawn. codex exports copyAuth() for exactly this (a COPY of ~/.codex/auth.json into
    // CODEX_HOME); without the call codex starts with an empty CODEX_HOME and dies instantly on
    // "No such file or directory (os error 2)" before emitting a single --json event.
    if (typeof adapter.copyAuth === 'function') await adapter.copyAuth(homeDir);

    // Adapters may be async (gemini fetches its key over HTTP in build()), so always await.
    let spawnSpec = await adapter.build({ sandbox: sandboxDir, prompt: 'Read TASK.md and begin.', model, home: homeDir });
    // staleResumes only counts RESUMES that produced nothing -- the very first spawn isn't a
    // resume, so it never counts toward the limit on its own (Addendum F: "Three RESUMES with no
    // new submission is stalled", not three attempts). `isResume` distinguishes the two.
    let staleResumes = 0;
    let isResume = false;

    for (;;) {
      // Addendum P: tick() first so a gap since the previous spawn (a sleeping machine between
      // resumes) is folded into suspendedMs BEFORE it's checked against the wall, never after.
      const wallMsLeft = wallMsLimit - tick();
      if (wallMsLeft <= 0) {
        stoppedBecause = 'time';
        break;
      }

      const beforeCount = allSubmissions.length;
      // eslint-disable-next-line no-await-in-loop
      transcript.push({
        ts: new Date().toISOString(),
        type: 'spawn',
        cmd: spawnSpec.cmd,
        args: spawnSpec.args || [],
        cwd: spawnSpec.cwd || sandboxDir,
        env: spawnSpec.env || {},
      });
      // Addendum Q rule 13 (codeWrites): a script-file mtime snapshot taken either side of this
      // spawn's whole supervision window -- see scanScriptMtimes()'s doc comment above.
      // eslint-disable-next-line no-await-in-loop
      const scriptMtimesBefore = await scanScriptMtimes(sandboxDir);
      const outcome = await superviseProcess({
        cmd: spawnSpec.cmd,
        args: spawnSpec.args || [],
        env: buildEnv(spawnSpec.env),
        // An adapter may name its own cwd (e.g. one that needs to run somewhere under `home`);
        // default to the sandbox, since that's where TASK.md/spec.json/HOUSE-RULES.md live.
        cwd: spawnSpec.cwd || sandboxDir,
        adminBase,
        adminToken,
        topRung,
        wallMsLeft,
        pollMs,
        maxBruTurns,
        onAdvance: applyAmendmentIfDue,
        // Addendum G: the baseline is per RUN, not per spawn -- `allSubmissions` is this climb's
        // own running total across every earlier spawn/resume, so a resume never re-reacts to
        // (re-advances for, or re-fails on) a submission an earlier spawn already handled.
        knownSubmissionsCount: allSubmissions.length,
        // Addendum P: same fake-clock injection as this loop's own tick() above, so a test can
        // simulate a sleep that happens DURING a spawn's own supervision window, not just between
        // spawns.
        now,
        onEvent: (entry) => transcript.push(entry),
      });
      // Addendum Q rule 13: diff the script-file mtime snapshot (codeWrites), and scan this
      // spawn's own stdout/stderr for grep/cat/sed invocations of HOUSE-RULES.md (docReads).
      // eslint-disable-next-line no-await-in-loop
      const scriptMtimesAfter = await scanScriptMtimes(sandboxDir);
      codeWrites += countScriptWrites(scriptMtimesBefore, scriptMtimesAfter);
      if ((outcome.stdout && outcome.stdout.length) || (outcome.stderr && outcome.stderr.length)) {
        sawAnyProcessOutput = true;
        docReads += docReadInvocationsIn(outcome.stdout) + docReadInvocationsIn(outcome.stderr);
      }
      // Addendum P: a sleep detected inside the spawn's own poll loop (supervise.js) is reported
      // back here and folded into this climb's total -- also nudges this loop's own tick() so the
      // very next iteration's wall check doesn't re-count the same gap as a fresh one.
      if (outcome.suspendedMs) {
        suspendedMs += outcome.suspendedMs;
        lastTickAt = now();
      }

      transcript.push({
        ts: new Date().toISOString(),
        type: 'exit',
        exitCode: outcome.exitCode,
        signal: outcome.signal,
        killedFor: outcome.killedFor,
      });

      allSubmissions = outcome.submissions;
      const gotNewSubmission = allSubmissions.length > beforeCount;
      const lastNew = gotNewSubmission ? allSubmissions[allSubmissions.length - 1] : null;

      // Addendum F budget: "tokensNovel = (input - cached) + output from the tool's own usage."
      // Unlike run.js's message-loop delta (which has to undo cumulative resend across turns of
      // ONE conversation), each CLI process reports its own usage for that process's own calls,
      // so summing per-spawn is exactly the novel-token count across resumes.
      // eslint-disable-next-line no-await-in-loop
      // A CLI that dies before emitting any usage event is a tooling/provider failure, not a
      // harness bug: record what the process actually said and end the climb as an error, so
      // result.json + transcript.jsonl still get written instead of the run vanishing in a throw.
      // Addendum G: supervise.js now SIGTERMs and drains for up to drainMs before SIGKILLing on a
      // fall/top/wall/overshoot, so outcome.stdout is the process's own drained result (its
      // `--output-format json` output, printed while wrapping up) in the common case, not an
      // empty stream -- parse it exactly as a clean exit's stdout. adapter.parseUsage() for `ai`
      // and `qwen` additionally falls back to the isolated home's session files when stdout itself
      // didn't carry usage (e.g. the drain window still wasn't enough); only when BOTH fail does it
      // return usageEstimated: true.
      const supervisedKill =
        outcome.killedFor === 'fail' ||
        outcome.killedFor === 'top' ||
        outcome.killedFor === 'wall' ||
        outcome.killedFor === 'overshoot' ||
        // Addendum J: the turn cap uses the same drain-then-kill (gracefulKillTree) as fall/top/
        // wall/overshoot, so it gets the same settle-and-retry usage read as they do.
        outcome.killedFor === 'turns';
      let usage;
      try {
        usage = await parseUsageSettling(adapter, outcome.stdout, homeDir, supervisedKill);
      } catch (err) {
        transcript.push({
          ts: new Date().toISOString(),
          type: 'usage-parse-error',
          message: err && err.message ? err.message : String(err),
          exitCode: outcome.exitCode,
          signal: outcome.signal,
          killedFor: outcome.killedFor,
          stdoutTail: String(outcome.stdout || '').slice(-4000),
          stderrTail: String(outcome.stderr || '').slice(-4000),
        });
        // Even with the drain, an adapter's own parseUsage can still throw (its session-file
        // fallback found nothing either). On a supervised kill the climb's outcome is already
        // decided by the submission that triggered it, so report zero/estimated usage for this
        // spawn rather than losing the whole run; a kill nobody asked for (killedFor null/'error')
        // is a genuine tooling failure instead.
        if (supervisedKill) {
          usage = {};
          usageEstimated = true;
        } else {
          stoppedBecause = 'error';
          break;
        }
      }
      tokensIn += usage.tokensIn || 0;
      tokensOut += usage.tokensOut || 0;
      tokensCached += usage.tokensCached || 0;
      tokensNovel += Math.max(0, (usage.tokensIn || 0) - (usage.tokensCached || 0)) + (usage.tokensOut || 0);
      if (usage.modelVersion) {
        modelVersion = usage.modelVersion;
        // Addendum F: "if it differs from the requested id the run is marked modelMismatch: true
        // ... Never silently accept a fallback model."
        if (model && usage.modelVersion !== model) modelMismatch = true;
      }
      if (usage.usageEstimated) usageEstimated = true;
      if (usage.sessionId) sessionId = usage.sessionId;

      if (tokensNovel >= budgetTokens) {
        stoppedBecause = 'budget';
        break;
      }
      // Addendum G: an overshoot is this harness double-advancing, never the agent falling off
      // anything -- it must never be scored as a fall ('fail') or a clean top ('top').
      if (outcome.killedFor === 'overshoot') {
        stoppedBecause = 'error';
        break;
      }
      if (outcome.killedFor === 'wall') {
        stoppedBecause = 'time';
        break;
      }
      // Addendum J: "Turn cap. 5000 bru requests per run, reported as stoppedBecause: 'turns'."
      if (outcome.killedFor === 'turns') {
        stoppedBecause = 'turns';
        break;
      }
      if (outcome.killedFor === 'fail' || (lastNew && lastNew.pass === false)) {
        stoppedBecause = 'fail';
        break;
      }
      if (outcome.killedFor === 'top' || (lastNew && lastNew.pass && lastNew.rung >= topRung)) {
        stoppedBecause = 'top';
        break;
      }
      if (outcome.killedFor === 'error' && !gotNewSubmission) {
        stoppedBecause = 'error';
        break;
      }

      // Clean exit, no fall, not the top: Addendum F says resume. A submission (pass, short of
      // the top) resets the stall streak -- only a run of resumes that produce NOTHING new counts
      // toward "stalled", and the streak only advances once we're actually resuming (not on the
      // very first spawn).
      if (gotNewSubmission) {
        staleResumes = 0;
      } else if (isResume) {
        staleResumes += 1;
      }
      if (staleResumes >= MAX_RESUMES_WITHOUT_SUBMISSION) {
        stoppedBecause = 'stalled';
        break;
      }

      resumes += 1;
      isResume = true;
      const currentRungGuess = allSubmissions.length
        ? allSubmissions[allSubmissions.length - 1].rung + (allSubmissions[allSubmissions.length - 1].pass ? 1 : 0)
        : 0;
      const resumeContext = {
        sandbox: sandboxDir,
        prompt: `Continue the climb; the current rung is ${currentRungGuess}. Read TASK.md again if you need to.`,
        model,
        home: homeDir,
      };
      let resumeSpec = null;
      if (sessionId && typeof adapter.resume === 'function') {
        try {
          // eslint-disable-next-line no-await-in-loop
          resumeSpec = await adapter.resume(sessionId, resumeContext);
        } catch {
          resumeSpec = null;
        }
      }
      // Addendum F: "otherwise a fresh session with the note" -- no session id to resume from, or
      // the adapter has no resume() worth calling, so start over with an explicit pointer at
      // where the climb actually stands.
      // eslint-disable-next-line no-await-in-loop
      spawnSpec = resumeSpec || (await adapter.build(resumeContext));
    }

    const wallMs = now() - startedAt;
    const passedNs = allSubmissions.filter((s) => s.pass).map((s) => s.rung);
    const rung = passedNs.length ? Math.max(...passedNs) : -1;
    const fidelityScores = allSubmissions.map((s) => s.fidelity).filter((v) => typeof v === 'number');
    const fidelity = fidelityScores.length ? fidelityScores.reduce((a, b) => a + b, 0) / fidelityScores.length : 0;

    const collectionDir = path.join(runDir, 'collection');
    await copyCollection(sandboxDir, collectionDir);
    const trap = await computeTrap(world, collectionDir);

    // Addendum J extends /admin/violations with `samples` ({ua, method, path}, up to 20, kept
    // here so a violation is still readable once the server is gone) and `adminProbes` (unauthorized
    // hits on the ADMIN port itself -- distinct from `violations`, which is public-API traffic with
    // a non-bru User-Agent). Read defensively, same as `violations` above: both default to
    // empty/zero until [api]'s admin.js emits them.
    let violations = 0;
    let violationSamples = [];
    let adminProbes = 0;
    try {
      const violationsBody = await adminGet(adminBase, '/admin/violations', adminToken);
      if (typeof violationsBody.count === 'number') violations = violationsBody.count;
      else if (Array.isArray(violationsBody.data)) violations = violationsBody.data.length;
      if (Array.isArray(violationsBody.samples)) {
        violationSamples = violationsBody.samples.slice(0, 20).map((s) => ({
          ua: s && s.ua != null ? s.ua : null,
          method: s && s.method != null ? s.method : null,
          path: s && s.path != null ? s.path : null,
        }));
      }
      if (typeof violationsBody.adminProbes === 'number') adminProbes = violationsBody.adminProbes;
    } catch {
      violations = 0;
    }

    // Addendum J: "any adminProbe voids the run" -- overrides whatever stoppedBecause was earned.
    if (adminProbes > 0) stoppedBecause = 'voided-admin-probe';

    // Addendum G: "Turns are counted at the API, not by the shim." codex's native round-three run
    // reported 0 turns because its shell didn't inherit the shim's PATH -- the shim never saw a
    // single invocation even though bru was genuinely being run. Turns is now the number of
    // requests in the admin log whose User-Agent starts with 'bruno-runtime/' (every genuine bru
    // invocation sends that, uniformly across drivers, regardless of how the CLI happened to reach
    // it). The shim's own turns.jsonl stays in the transcript as a secondary log only.
    const shimTurns = await readShimTurns(sandboxDir);
    for (const t of shimTurns) transcript.push({ ts: t.ts, type: 'turn', argv: t.argv });
    transcript.sort((a, b) => String(a.ts).localeCompare(String(b.ts)));

    let turns = 0;
    try {
      const logBody = await adminGet(adminBase, '/admin/log', adminToken);
      const entries = Array.isArray(logBody.data) ? logBody.data : [];
      turns = entries.filter((e) => typeof e.ua === 'string' && e.ua.startsWith('bruno-runtime/')).length;
    } catch {
      turns = 0;
    }

    const result = {
      // Addendum G: "the board groups rows by ladder version and marks the current one" only
      // works if a run records which ladder it climbed. Stamp it here, at write time, so
      // score.js/board.js read a real version instead of falling back to 'unknown' forever.
      version: LADDER_VERSION,
      model: model || cliName || 'fake',
      // cliName names the --cli flag for a real run; a test injecting an adapter object directly
      // (climb({cli: ...})) has no cliName, so fall back to the adapter's own declared name.
      driver: `cli:${cliName || adapter.name || 'fake'}`,
      modelVersion,
      seed,
      attempt,
      rung,
      turns,
      tokensIn,
      tokensOut,
      tokensNovel,
      tokensBilled: tokensIn + tokensOut,
      cacheReadTokens: tokensCached,
      // Addendum F: "Trims are the CLI's own compaction; not observable uniformly, so the column
      // is resumes."
      trims: 0,
      wallMs,
      // Addendum P: total gap time folded out of the wall check as "the machine slept," not the
      // CLI working -- 0 for every ordinary run, nonzero only when a tick-to-tick gap (between
      // spawns here, or between poll ticks inside supervise.js) exceeded SUSPEND_GAP_MS (5 min).
      suspendedMs,
      fidelity,
      trap,
      submissions: allSubmissions,
      stoppedBecause,
      driverError: null,
      violations,
      violationSamples,
      adminProbes,
      resumes,
      modelMismatch,
      usageEstimated,
      // Addendum Q rule 13 (CLI-driver fallback -- mtime scan / transcript text scan, see the
      // block above climb()). docReads is null, not 0, when this run's CLI never printed anything
      // observable at all -- "we saw nothing" is not the same claim as "we saw zero reads."
      codeWrites,
      docReads: sawAnyProcessOutput ? docReads : null,
    };

    await writeFile(path.join(runDir, 'transcript.jsonl'), `${transcript.map((t) => JSON.stringify(t)).join('\n')}\n`);
    await writeFile(path.join(runDir, 'result.json'), JSON.stringify(result, null, 2));

    return result;
  } finally {
    await server.stop();
  }
}

